import { expect, test } from '@playwright/test'

test('loads source webfonts inside the script-free opaque resource sandbox', async ({ page }) => {
  await page.goto('http://127.0.0.1:4317/health')
  await page.setContent('<iframe title="font-qa" sandbox="" style="width:960px;height:540px" src="http://127.0.0.1:4317/api/v1/resources/preview/font-qa"></iframe>')
  const frame = page.frameLocator('iframe[title="font-qa"]')
  await expect(frame.locator('[data-resource-text]').first()).toBeVisible()
  await expect.poll(async () => frame.locator('html').evaluate(() => [...document.fonts].filter(font => font.family.includes('fp-') && font.status === 'loaded').length)).toBeGreaterThan(0)
  await expect(frame.locator('[data-resource-text]').first()).toHaveCSS('font-family', /fp-/)
})

test('searches layouts, remakes a selected page and scopes a visual edit', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByTitle('Slidev preview')).toBeVisible()
  await expect(page.locator('.current-deck-pages .slide-item').first()).toBeVisible()
  await page.getByRole('tab', { name: '版式', exact: true }).click()
  await expect(page.getByRole('heading', { name: '版式与逻辑图' })).toBeVisible()
  const searched = page.waitForResponse(response => response.url().includes('/api/v1/resources?') && new URL(response.url()).searchParams.get('query') === '流程')
  await page.getByLabel('搜索版式', { exact: true }).fill('流程')
  const results = await (await searched).json() as { items: { id: string }[] }
  const card = page.locator('.resource-card').first()
  await expect(card).toHaveAttribute('data-resource-id', results.items[0]!.id)
  await expect(card).toBeVisible()
  await expect(card.locator('iframe')).toBeVisible()
  await expect(card.locator('img')).toHaveCount(0)
  await card.getByRole('button', { name: /放大预览/ }).click()
  const preview = page.getByRole('dialog', { name: '版式现场预览' })
  await expect(preview).toBeVisible()
  await expect(preview.locator('iframe')).toBeVisible()
  const firstId = await preview.locator('header p').textContent()
  await preview.getByRole('button', { name: '下一页' }).click()
  await expect(preview.locator('header p')).not.toHaveText(firstId!)
  await page.screenshot({ path: '/tmp/fastppt-resource-live-preview.png' })
  await preview.getByRole('button', { name: '关闭预览' }).click()
  await expect(preview).toBeHidden()
  await card.getByRole('button', { name: /用于第/ }).click()
  const dialog = page.getByRole('dialog', { name: /第 1 页/ })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('更换版式', { exact: true })).toBeVisible()
  const sent = page.waitForRequest(request => request.method() === 'POST' && /\/sessions\/.*\/messages$/.test(request.url()))
  await dialog.getByRole('button', { name: '创建分支并修改' }).click()
  const request = await sent
  expect((request.postDataJSON() as { content: string }).content).toContain('fastppt-layout-reference')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: '框选修改', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '框选修改', exact: true }).click()
  const selection = page.getByRole('application')
  const box = await selection.boundingBox()
  expect(box).toBeTruthy()
  await page.mouse.move(box!.x + box!.width * .2, box!.y + box!.height * .2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width * .6, box!.y + box!.height * .6)
  await page.mouse.up()
  await expect(page.getByRole('dialog')).toContainText('选区：左 20% · 上 20% · 宽 40% · 高 40%')
  await page.screenshot({ path: '/tmp/fastppt-workspace-visual-edit.png' })
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('tab', { name: '对话', exact: true }).click()
  await page.locator('.slide-item').first().click({ button: 'right' })
  await page.getByRole('menuitem', { name: '使用版式 / 逻辑图重做' }).click()
  await expect(page.getByRole('dialog').getByLabel('搜索版式', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  expect(errors).toEqual([])
})
