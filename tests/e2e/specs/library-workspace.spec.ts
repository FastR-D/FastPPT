import { expect, test } from '@playwright/test'

test('renders layout cards and enlarged previews from source without screenshot endpoints', async ({ page }) => {
  const screenshots: string[] = [], errors: string[] = []
  page.on('request', request => { if (/\/resources\/(?:thumbnail|original)\//.test(request.url())) screenshots.push(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('tab')).toHaveText(['对话', '编辑', '版式', '画盘', '动画', '备注', '主题'])
  await page.getByRole('tab', { name: '版式', exact: true }).click()
  const card = page.locator('.resource-card').first()
  await expect(card.locator('iframe')).toBeVisible()
  const id = await card.getAttribute('data-resource-id')
  const frame = page.frameLocator(`.resource-card[data-resource-id="${id}"] iframe`)
  await expect(frame.locator('main > div')).toBeVisible()
  await expect(card.locator('img')).toHaveCount(0)
  expect(await card.locator('iframe').getAttribute('sandbox')).toBe('')
  expect(await page.locator('.resource-card iframe').count()).toBeLessThan(await page.locator('.resource-card').count())
  const last = page.locator('.resource-card').last()
  await last.scrollIntoViewIfNeeded()
  await expect(last.locator('iframe')).toBeVisible()
  await card.scrollIntoViewIfNeeded()
  // Opening the full-size view mounts another live renderer with no stored image.
  await card.getByRole('button', { name: /放大预览/ }).click()
  const dialog = page.getByRole('dialog', { name: '版式现场预览' })
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('iframe')).toHaveAttribute('src', new RegExp(`/preview/${id}`))
  await dialog.getByRole('button', { name: '下一页' }).click()
  await expect(dialog.locator('iframe')).not.toHaveAttribute('src', new RegExp(`/preview/${id}`))
  await dialog.getByRole('button', { name: '关闭预览' }).click()
  await page.getByLabel('搜索版式', { exact: true }).fill('流程')
  await expect.poll(() => page.locator('.resource-grid').getAttribute('aria-busy')).toBe('false')
  await expect(page.locator('.resource-card').first().locator('iframe')).toBeVisible()
  await page.screenshot({ path: '/tmp/fastppt-live-layout-gallery.png' })
  expect(screenshots).toEqual([])
  expect(errors).toEqual([])
})

test('keeps seven workspace tabs and direct creation actions and a compact preview toolbar without presenter mode', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('tab')).toHaveCount(7)
  const preview = page.locator('.preview-panel')
  await expect(preview.getByRole('button', { name: '导出 PPTX', exact: true })).toBeVisible()
  await expect(preview.getByRole('button', { name: '全屏', exact: true })).toHaveCount(0)
  await expect(preview.getByRole('button', { name: '新窗口', exact: true })).toHaveCount(0)
  await expect(preview.getByRole('button', { name: '重启预览', exact: true })).toBeHidden()
  await preview.locator('.preview-more > summary').click()
  await expect(preview.getByRole('button', { name: '重启预览', exact: true })).toBeVisible()
  await expect(preview.getByText('导出选项', { exact: true })).toBeVisible()
  await preview.locator('.preview-more > summary').click()
  await page.getByRole('tab', { name: '备注', exact: true }).click()
  await expect(page.getByRole('heading', { name: '讲稿备注' })).toBeVisible()
  await page.keyboard.press('Control+Shift+P')
  const commands = page.getByRole('dialog', { name: '命令面板' })
  await expect(commands.getByRole('button', { name: '新建演示文稿' })).toBeVisible()
  await expect(commands.getByRole('button', { name: /^(进入演示|开始演示|打开演示)$/ })).toHaveCount(0)
  await commands.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('tab', { name: '对话', exact: true }).click()
  await page.screenshot({ path: '/tmp/fastppt-compact-workspace.png' })
})
